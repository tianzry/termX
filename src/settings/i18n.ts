/** 设置中心文案查找；en 缺键回落 zh-CN，再回落 key 本身。 */
export function settingsT(
  lang: UiLanguage,
  key: string,
  params?: Record<string, string | number>,
): string {
  let text = (lang === "en" ? en[key] : undefined) ?? zhCN[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.split(`{${k}}`).join(String(v));
    }
  }
  return text;
}
